// splices banhmi/audio.js (sound engine + master chain) with the Cút lộn xào me score (_score.txt) -> audio.js
// Usage: node _build_audio.js && node audio.js && node audio_measure.js   (measure = ffmpeg ebur128 per window -> audio_report.txt)
const fs = require('fs');
const src = fs.readFileSync(__dirname + '/audio_banhmi_src.js', 'utf8').split(/\r?\n/);
let head = src.slice(0, 749).join('\n');   // lines 1..749: constants, DSP, instruments, SFX, buses, put(), lead(), tranhNote()
const rep = (s, a, b) => { if (!s.includes(a)) throw new Error('missing: ' + a); return s.replace(a, b); };
head = rep(head, '(30 s)', '(engine from banhmi/audio.js; this build: Cút lộn xào me, 60.000 s)');
head = rep(head, '30.0 s)', '60.000 s)');
head = rep(head, 'const DUR = 30.0;', 'const DUR = 60.0;');
head = rep(head, 'const BEAT = 0.5;            // 120 BPM', 'const BEAT = 60 / 128;       // 128 BPM');
head = rep(head, 'const CUT = 28.0;            // hard cut to silence', 'const CUT = 91 * BEAT;       // 42.65625 hard cut to silence (beat 91)');
head = rep(head, 'const RESUME = 28.5;         // bite', 'const RESUME = 92 * BEAT;    // 43.125 the bite (beat 92, shots.js BITE)');
const score = fs.readFileSync(__dirname + '/_score.txt', 'utf8');
let master = src.slice(937, 1075).join('\n');          // lines 938..1075: master chain + WAV writer
// per-section music trim (20 ms ramps ending on the cut): hook 0.85, act I 0.8, gag1 0.72, cooking 0.85, gag2 0.72, how-to-eat 0.8,
// tension s10/s11 0.95, after the bite 0.72 (sparse around the bite), farewell 0.8, CTA 0.92
master = rep(master, 'pw([[0, 0.78], [7.98, 0.78], [8.0, 0.88], [25.98, 0.88], [26.0, 1.0], [30, 1.0]], t)',
  'pw([[0, 0.85], [1.855, 0.85], [1.875, 0.8], [9.355, 0.8], [9.375, 0.72], [13.105, 0.72], [13.125, 0.85], [26.23, 0.85], [26.25, 0.72], [29.98, 0.72], [30.0, 0.8], ' +
  '[33.73, 0.8], [33.75, 0.95], [42.65625, 0.95], [43.125, 0.72], [47.7925, 0.72], [47.8125, 0.8], [54.82375, 0.8], [54.84375, 0.92], [60, 0.92]], t)');
master = rep(master, 'FADE0 = 29.15', 'FADE0 = 59.0');
// ceiling -1.8 dB (spec: true peak <= -1.6 dBTP measured by ffmpeg ebur128; keep 0.2 dB margin for its rounding / 4x vs ffmpeg oversampling)
master = rep(master, 'const CEIL = Math.pow(10, -1.6 / 20);', 'const CEIL = Math.pow(10, -1.8 / 20);');
master = rep(master, 'const lim = Math.pow(10, -1.5 / 20);', 'const lim = Math.pow(10, -1.7 / 20);');
const tail = `
// (f) report
const dbfs = (x) => (x > 0 ? (20 * Math.log10(x)).toFixed(1) : '-inf');
function stats(t0, t1) {
  const a = Math.round(t0 * SR), b = Math.min(N, Math.round(t1 * SR));
  let pk = 0, ss = 0, mg = 1;
  for (let i = a; i < b; i++) { pk = Math.max(pk, Math.abs(mL[i]), Math.abs(mR[i])); ss += mL[i] * mL[i] + mR[i] * mR[i]; mg = Math.min(mg, LIMG[i]); }
  return { peak: dbfs(pk), rms: dbfs(Math.sqrt(ss / (2 * Math.max(1, b - a)))), gr: (20 * Math.log10(mg)).toFixed(1) };
}
console.log('wrote', OUT, '(' + DUR + 's, ' + SR + ' Hz, stereo, 16-bit)');
for (const [name, a, b] of [['whole', 0, DUR], ['0-2', 0, 2], ['2-10', 2, 10], ['10-20', 10, 20], ['20-30', 20, 30], ['30-40', 30, 40], ['40-42.656', 40, CUT],
  ['SILENCE 42.656-43.125', CUT, RESUME], ['bite 43.125-43.6', RESUME, 43.6], ['43-48', 43, 48], ['48-55', 48, 55], ['55-60', 55, DUR]]) {
  const s = stats(a, b); console.log(name.padEnd(22), 'peak', s.peak.padStart(6), 'dBFS   rms', s.rms.padStart(6), 'dBFS   limiter GR', s.gr.padStart(5), 'dB');
}
{ // where does the limiter work more than 0.5 dB?
  const ev = []; let cur = null;
  for (let i = 0; i < N; i++) { const g = LIMG[i]; if (g < 0.944) { if (!cur || i - cur.e > SR * 0.05) { cur = { s: i, e: i, m: g }; ev.push(cur); } else { cur.e = i; cur.m = Math.min(cur.m, g); } } }
  console.log('limiter >0.5 dB at:', ev.length ? ev.map((e) => (e.s / SR).toFixed(2) + 's ' + (20 * Math.log10(e.m)).toFixed(1) + 'dB').join(', ') : 'nowhere');
}
`;
fs.writeFileSync(__dirname + '/audio.js', '// Cút lộn xào me soundtrack (60.000 s, 128 BPM, E-minor pentatonic night-Saigon deep-house / lo-fi): banhmi/audio.js engine + master chain + new score.\n// Generated by _build_audio.js from audio_banhmi_src.js + _score.txt. Edit _score.txt (CUES table at its top), then rebuild.\n' + head + '\n' + score + '\n' + master + '\n' + tail);
console.log('audio.js built');
