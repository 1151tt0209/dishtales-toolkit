// splices banhmi/audio.js (sound engine + master chain) with the Bánh bò nướng score (_score.txt) -> audio.js
// Usage: node _build_audio.js && node audio.js   (DEBUG=1 node audio.js prints limiter gain reduction per window)
const fs = require('fs');
const src = fs.readFileSync(__dirname + '/audio_banhmi_src.js', 'utf8').split(/\r?\n/);
let head = src.slice(0, 749).join('\n');   // lines 1..749: constants, DSP, instruments, SFX, buses, put(), lead(), tranhNote()
const rep = (s, a, b) => { if (!s.includes(a)) throw new Error('missing: ' + a); return s.replace(a, b); };
head = rep(head, '(30 s)', '(engine from banhmi/audio.js; this build: Bánh bò nướng lá dứa, 62.308 s)');
head = rep(head, '30.0 s)', '62.308 s)');
head = rep(head, 'const DUR = 30.0;', 'const DUR = 62.308;');
head = rep(head, 'const BEAT = 0.5;            // 120 BPM', 'const BEAT = 60 / 104;       // 104 BPM');
head = rep(head, 'const CUT = 28.0;            // hard cut to silence', 'const CUT = 46.154;          // hard cut to silence (beat 80)');
head = rep(head, 'const RESUME = 28.5;         // bite', 'const RESUME = 46.731;       // the bite (beat 81, shots.js BITE)');
const score = fs.readFileSync(__dirname + '/_score.txt', 'utf8');
let master = src.slice(937, 1075).join('\n');          // lines 938..1075: master chain + WAV writer
// per-act music trim: act I light 0.8, act II 0.92, the tear 1.0, after the bite 0.85, CTA 0.95 (20 ms ramps ending on the cut)
master = rep(master, 'pw([[0, 0.78], [7.98, 0.78], [8.0, 0.88], [25.98, 0.88], [26.0, 1.0], [30, 1.0]], t)',
  'pw([[0, 0.8], [24.211, 0.8], [24.231, 0.92], [36.903, 0.92], [36.923, 0.95], [46.154, 0.95], [46.731, 0.85], [57.095, 0.85], [57.115, 0.95], [62.308, 0.95]], t)');
master = rep(master, 'FADE0 = 29.15', 'FADE0 = 61.2');
const tail = `
// (f) report
const dbfs = (x) => (x > 0 ? (20 * Math.log10(x)).toFixed(1) : '-inf');
function stats(t0, t1) {
  const a = Math.round(t0 * SR), b = Math.min(N, Math.round(t1 * SR));
  let pk = 0, ss = 0, mg = 1;
  for (let i = a; i < b; i++) { pk = Math.max(pk, Math.abs(mL[i]), Math.abs(mR[i])); ss += mL[i] * mL[i] + mR[i] * mR[i]; mg = Math.min(mg, LIMG[i]); }
  return { peak: dbfs(pk), rms: dbfs(Math.sqrt(ss / (2 * Math.max(1, b - a)))), gr: (20 * Math.log10(mg)).toFixed(1) };
}
console.log('wrote', OUT, '(' + DUR + 's, ' + SR + ' Hz, stereo, 16-bit)');
for (const [name, a, b] of [['whole', 0, DUR], ['ActI 0-24.23', 0, 24.231], [' hook 0-2.31', 0, 2.308], [' oven 17.3-24.2', 17.308, 24.231],
  ['ActII 24.23-43.85', 24.231, 43.846], [' gag2 32.3-34.6', 32.308, 34.615], [' drop 34.6-36.9', 34.615, 36.923], [' tear 36.9-43.8', 36.923, 43.846],
  ['s11 43.85-46.15', 43.846, 46.154], ['SILENCE 46.154-46.731', 46.154, 46.731], ['bite 46.731-47.25', 46.731, 47.25],
  ['ActIII 46.73-57.1', 46.731, 57.115], ['CTA 57.1-62.3', 57.115, DUR], ['end 61.8-62.3', 61.8, DUR]]) {
  const s = stats(a, b); console.log(name.padEnd(22), 'peak', s.peak.padStart(6), 'dBFS   rms', s.rms.padStart(6), 'dBFS   limiter GR', s.gr.padStart(5), 'dB');
}
{ // where does the limiter work more than 0.5 dB?
  const ev = []; let cur = null;
  for (let i = 0; i < N; i++) { const g = LIMG[i]; if (g < 0.944) { if (!cur || i - cur.e > SR * 0.05) { cur = { s: i, e: i, m: g }; ev.push(cur); } else { cur.e = i; cur.m = Math.min(cur.m, g); } } }
  console.log('limiter >0.5 dB at:', ev.length ? ev.map((e) => (e.s / SR).toFixed(2) + 's ' + (20 * Math.log10(e.m)).toFixed(1) + 'dB').join(', ') : 'nowhere');
}
`;
fs.writeFileSync(__dirname + '/audio.js', '// Bánh bò nướng lá dứa soundtrack (62.308 s, 104 BPM, C major tropical folk-pop): banhmi/audio.js engine + master chain + new score.\n// Generated by _build_audio.js from audio_banhmi_src.js + _score.txt. Edit _score.txt (cue table at its top), then rebuild.\n' + head + '\n' + score + '\n' + master + '\n' + tail);
console.log('audio.js built');
