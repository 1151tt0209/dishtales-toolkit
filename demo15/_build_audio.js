// splices banhmi/audio.js (sound engine + master chain) with the 15 s demo score -> audio.js
const fs = require('fs');
const src = fs.readFileSync(__dirname + '/audio_banhmi_src.js', 'utf8').split(/\r?\n/);
let head = src.slice(0, 749).join('\n');   // lines 1..749: constants, DSP, instruments, SFX, buses, put(), lead(), tranhNote()
const rep = (s, a, b) => { if (!s.includes(a)) throw new Error('missing: ' + a); return s.replace(a, b); };
head = rep(head, 'const DUR = 30.0;', 'const DUR = 15.0;');
head = rep(head, 'const BEAT = 0.5;            // 120 BPM', 'const BEAT = 60 / 108;       // 108 BPM');
head = rep(head, 'const CUT = 28.0;            // hard cut to silence', 'const CUT = 10.0;            // hard cut to silence');
head = rep(head, 'const RESUME = 28.5;         // bite', 'const RESUME = 10.45;        // bite');
const score = fs.readFileSync(__dirname + '/_score.txt', 'utf8');
let master = src.slice(937, 1075).join('\n');          // lines 938..1075: master chain + WAV writer
master = rep(master, 'pw([[0, 0.78], [7.98, 0.78], [8.0, 0.88], [25.98, 0.88], [26.0, 1.0], [30, 1.0]], t)', 'pw([[0, 0.85], [11.1, 0.85], [11.12, 1.0], [15, 1.0]], t)');
master = rep(master, 'FADE0 = 29.15', 'FADE0 = 14.55');
const tail = `
// (f) report
const dbfs = (x) => (x > 0 ? (20 * Math.log10(x)).toFixed(1) : '-inf');
function stats(t0, t1) {
  const a = Math.round(t0 * SR), b = Math.min(N, Math.round(t1 * SR));
  let pk = 0, ss = 0;
  for (let i = a; i < b; i++) { pk = Math.max(pk, Math.abs(mL[i]), Math.abs(mR[i])); ss += mL[i] * mL[i] + mR[i] * mR[i]; }
  return { peak: dbfs(pk), rms: dbfs(Math.sqrt(ss / (2 * Math.max(1, b - a)))) };
}
console.log('wrote', OUT, '(' + DUR + 's, ' + SR + ' Hz, stereo, 16-bit)');
for (const [name, a, b] of [['whole', 0, 15], ['hook 0-2.8', 0, 2.8], ['pieces 2.8-4.4', 2.8, 4.4], ['fold 4.4-6.7', 4.4, 6.7], ['hero 6.7-8.3', 6.7, 8.3], ['wrap 8.3-10', 8.3, 10], ['gap 10.0-10.45', 10.0, 10.45], ['bite 10.45-10.9', 10.45, 10.9], ['CTA 11.1-14.4', 11.1, 14.4], ['end 14.6-15', 14.6, 15]]) {
  const s = stats(a, b); console.log(name.padEnd(16), 'peak', s.peak.padStart(6), 'dBFS   rms', s.rms.padStart(6), 'dBFS');
}
`;
fs.writeFileSync(__dirname + '/audio.js', '// 15 s demo soundtrack: banhmi/audio.js engine + master chain, new score (108 BPM). Generated by _build_audio.js from audio_banhmi_src.js + _score.txt.\n' + head + '\n' + score + '\n' + master + '\n' + tail);
console.log('audio.js built');
